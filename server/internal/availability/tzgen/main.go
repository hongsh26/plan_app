// Command tzgen은 활동 시간 설정이 받는 지역 IANA 시간대 목록(zones_gen.go)을 만든다.
//
// 원본은 실행한 Go toolchain의 $GOROOT/lib/time/zoneinfo.zip이다. time/tzdata가 내장하는 것과 같은
// 데이터라 목록과 실제 로딩 결과가 어긋나지 않는다. Go를 올린 뒤 `go generate ./internal/availability`로
// 다시 만든다. 허용 규칙은 availability.ValidTimeZone 문서에 있다.
package main

import (
	"archive/zip"
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
	"strings"
)

// zoneNamePattern은 availability.zoneNamePattern과 같아야 한다.
var zoneNamePattern = regexp.MustCompile(`^[A-Z][A-Za-z_]+(/[A-Za-z0-9_+\-]+){1,2}$`)

func main() {
	r, err := zip.OpenReader(filepath.Join(runtime.GOROOT(), "lib", "time", "zoneinfo.zip"))
	if err != nil {
		fmt.Fprintln(os.Stderr, "zoneinfo.zip을 열 수 없다:", err)
		os.Exit(1)
	}
	defer r.Close()
	var names []string
	for _, f := range r.File {
		n := f.Name
		if !zoneNamePattern.MatchString(n) || strings.HasPrefix(n, "Etc/") {
			continue
		}
		names = append(names, n)
	}
	sort.Strings(names)

	var b bytes.Buffer
	b.WriteString("// Code generated by tzgen; DO NOT EDIT.\n\npackage availability\n\n")
	b.WriteString("// regionZones는 내장 tzdata의 지역 IANA 시간대 이름이다(Etc/·별칭·고정 offset 제외).\n")
	b.WriteString("var regionZones = map[string]struct{}{\n")
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: {},\n", n)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile("zones_gen.go", src, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
